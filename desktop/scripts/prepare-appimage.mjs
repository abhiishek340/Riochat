#!/usr/bin/env node
// Prepares the Linux AppImage tooling before `tauri build`.
//
//   node scripts/prepare-appimage.mjs [architecture]     (default: x86_64)
//
// Downloads the bundler's helper tools into the tauri cache (with retries) and
// replaces the cached linuxdeploy with a wrapper that always excludes the
// Wayland client libraries. Bundled copies of these break EGL on newer Wayland
// systems and produce a blank window.
//
// Set LINUXDEPLOY_DEBUG_LOG=<file> to log every wrapper invocation.

import { chmodSync, existsSync, mkdirSync, renameSync, writeFileSync } from "node:fs";
import os from "node:os";
import path from "node:path";
import { isMain } from "./lib/util.mjs";

export const EXCLUDED_LIBRARIES = [
  "libwayland-client.so.0",
  "libwayland-cursor.so.0",
  "libwayland-egl.so.1",
  "libwayland-server.so.0",
];

export function cacheDir(env = process.env, home = os.homedir()) {
  if (env.TAURI_BUNDLER_TOOLS_DIR) return env.TAURI_BUNDLER_TOOLS_DIR;
  const base = env.XDG_CACHE_HOME || path.join(home, ".cache");
  return path.join(base, "tauri");
}

export function tools(arch) {
  const tauriReleases = "https://github.com/tauri-apps/binary-releases/releases/download";
  return [
    { file: `linuxdeploy-${arch}.AppImage`, url: `${tauriReleases}/linuxdeploy/linuxdeploy-${arch}.AppImage`, exec: true },
    {
      file: "linuxdeploy-plugin-appimage.AppImage",
      url: `https://github.com/linuxdeploy/linuxdeploy-plugin-appimage/releases/download/continuous/linuxdeploy-plugin-appimage-${arch}.AppImage`,
      exec: true,
    },
    {
      file: "linuxdeploy-plugin-gtk.sh",
      url: "https://raw.githubusercontent.com/tauri-apps/linuxdeploy-plugin-gtk/master/linuxdeploy-plugin-gtk.sh",
      exec: true,
    },
    {
      file: "linuxdeploy-plugin-gstreamer.sh",
      url: "https://raw.githubusercontent.com/tauri-apps/linuxdeploy-plugin-gstreamer/master/linuxdeploy-plugin-gstreamer.sh",
      exec: true,
    },
  ];
}

/** The wrapper script that stands in for linuxdeploy. */
export function renderWrapper({ realPath, libraries = EXCLUDED_LIBRARIES }) {
  const excludes = libraries.map((l) => `  --exclude-library "${l}" \\`).join("\n");
  const quoted = realPath.replace(/'/g, "'\\''");
  return `#!/bin/sh
# Generated by prepare-appimage.mjs: runs the real linuxdeploy, always excluding
# the Wayland client libraries (bundling them breaks EGL on newer systems).
REAL='${quoted}'
if [ -n "$LINUXDEPLOY_DEBUG_LOG" ]; then
  printf '%s\\n' "linuxdeploy $*" >> "$LINUXDEPLOY_DEBUG_LOG"
fi
# the GTK and GStreamer plugins call back into linuxdeploy through this variable
export LINUXDEPLOY="$0"
exec "$REAL" \\
${excludes}
  "$@"
`;
}

async function download(url, dest, attempts = 4, fetchImpl = globalThis.fetch) {
  let lastError;
  for (let i = 1; i <= attempts; i++) {
    try {
      const res = await fetchImpl(url, { redirect: "follow" });
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      writeFileSync(dest, Buffer.from(await res.arrayBuffer()));
      return;
    } catch (e) {
      lastError = e;
      await new Promise((r) => setTimeout(r, 500 * i));
    }
  }
  throw new Error(`cannot download ${url}: ${lastError.message}`);
}

export async function prepare({ arch = "x86_64", env = process.env } = {}) {
  const dir = cacheDir(env);
  mkdirSync(dir, { recursive: true });
  for (const t of tools(arch)) {
    const dest = path.join(dir, t.file);
    if (!existsSync(dest)) {
      console.log(`downloading ${t.file}`);
      await download(t.url, dest);
    }
    if (t.exec) chmodSync(dest, 0o755);
  }
  const wrapper = path.join(dir, `linuxdeploy-${arch}.AppImage`);
  const real = path.join(dir, `linuxdeploy-${arch}.real.AppImage`);
  if (!existsSync(real)) renameSync(wrapper, real);
  writeFileSync(wrapper, renderWrapper({ realPath: real }));
  chmodSync(wrapper, 0o755);
  console.log(`installed the linuxdeploy wrapper at ${wrapper}`);
}

if (isMain(import.meta.url)) {
  try {
    const argv = process.argv.slice(2);
    if (argv.length > 1) throw new Error("usage: prepare-appimage.mjs [architecture]");
    await prepare({ arch: argv[0] });
  } catch (e) {
    console.error(`prepare-appimage: ${e.message}`);
    process.exit(1);
  }
}
